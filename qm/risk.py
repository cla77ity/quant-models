"""
qm.risk — метрики доходности и риска.

Все функции получают ДНЕВНЫЕ доходности стратегии: массив чисел вида 0.012 (= +1.2% за день), -0.004 (= -0.4%).
Почему дневные: так считают почти все фонды; годовые цифры получаются «масштабированием» (× 252 торговых дня).

Шпаргалка по обозначениям в коде:
    r      — массив дневных доходностей (numpy array или pandas Series)
    np.mean(r)        — среднее
    np.std(r, ddof=1) — стандартное отклонение «по выборке» (делим на n-1, а не на n)
    252    — число торговых дней в году
"""
import numpy as np

DAYS = 252  # торговых дней в году


# ------------------------------------------------------------------ доходность

def equity_curve(r):
    """Кривая капитала: во сколько раз вырос 1 доллар.
    Доходности перемножаются, а не складываются: +10%, потом -10% = 1.1 × 0.9 = 0.99 (минус 1%).
    np.cumprod — «накопленное произведение»: [1.1, 0.9] → [1.1, 0.99]."""
    return np.cumprod(1 + np.asarray(r))


def cagr(r):
    """Среднегодовой рост (CAGR, compound annual growth rate).
    Итог за весь период превращаем в «одинаковый рост каждый год»: итог ** (1 / лет) - 1.
    Пример: капитал вырос в 2 раза за 10 лет → 2 ** (1/10) - 1 = 7.2% в год."""
    r = np.asarray(r)
    years = len(r) / DAYS
    return equity_curve(r)[-1] ** (1 / years) - 1


# ------------------------------------------------------------------ риск

def volatility(r):
    """Годовая волатильность = стандартное отклонение дневных доходностей × √252.
    Почему корень: дисперсия независимых дней складывается (× 252), а волатильность — это корень из дисперсии.
    Смысл: «в обычный год результат гуляет примерно ± на столько». 10% — спокойный портфель, 20% — как индекс акций."""
    return np.std(r, ddof=1) * np.sqrt(DAYS)


def sharpe(r):
    """Коэффициент Шарпа = средняя доходность / волатильность (в годовом выражении).
    mean × 252 / (std × √252) = mean / std × √252.
    Здесь доходности уже «сверх безрисковой ставки» (в CFD/фьючерсах стоимость денег вычтена), поэтому ставку не вычитаем.
    Ориентиры: < 0.3 почти ничего, 0.5 — как индекс в долгую, 1+ — сильно, 3+ — скорее ошибка в бэктесте."""
    r = np.asarray(r)
    sd = np.std(r, ddof=1)
    return np.mean(r) / sd * np.sqrt(DAYS) if sd > 0 else 0.0


def sortino(r):
    """Как Sharpe, но риском считаются только ПАДЕНИЯ (рост не «наказывается»).
    Знаменатель — «нижнее отклонение»: корень из среднего квадрата отрицательных доходностей."""
    r = np.asarray(r)
    downside = np.sqrt(np.mean(np.minimum(r, 0) ** 2))
    return np.mean(r) / downside * np.sqrt(DAYS) if downside > 0 else 0.0


def drawdown_series(r):
    """Просадка на каждый день: насколько капитал ниже своего предыдущего максимума (0 … -1).
    np.maximum.accumulate — «бегущий максимум»: [1, 3, 2, 5] → [1, 3, 3, 5]."""
    eq = equity_curve(r)
    peak = np.maximum.accumulate(np.concatenate([[1.0], eq]))[1:]   # стартовый капитал (1.0) тоже считается пиком
    return eq / peak - 1


def max_drawdown(r):
    """Максимальная просадка — самое глубокое падение от пика (например -0.28 = -28%).
    Главная «болевая» метрика: именно она решает, выдержит ли инвестор (или правило проп-фирмы) стратегию."""
    return drawdown_series(r).min()


def calmar(r):
    """Calmar = CAGR / |максимальная просадка|. Сколько годового роста приходится на единицу худшей боли."""
    dd = max_drawdown(r)
    return cagr(r) / -dd if dd < 0 else np.nan


def t_stat(r):
    """t-статистика среднего: насколько среднее отличается от нуля с учётом шума = mean / (std / √n).
    |t| > 2 — примерно «вряд ли случайность» (95%). Связь с Sharpe: t ≈ Sharpe × √лет.
    Поэтому Sharpe 0.5 становится значимым только примерно за 16 лет данных."""
    r = np.asarray(r)
    sd = np.std(r, ddof=1)
    return np.mean(r) / (sd / np.sqrt(len(r))) if sd > 0 else 0.0


# ------------------------------------------------------------------ хвостовой риск (то, что считает риск-менеджер фонда)

def var_historical(r, level=0.99):
    """VaR (Value at Risk) по истории: «в 99% дней мы теряем не больше X».
    Это просто 1%-й квантиль дневных доходностей (99% дней лучше него). Возвращается положительным числом потерь.
    Слабость: ничего не говорит о том, насколько плохо в оставшийся 1%."""
    return -np.quantile(np.asarray(r), 1 - level)


def cvar_historical(r, level=0.99):
    """CVaR / Expected Shortfall: средний убыток В ТЕ САМЫЕ худшие 1% дней.
    Отвечает на вопрос «если плохой день всё-таки случился — сколько в среднем теряем». Регуляторы банков (Basel)
    перешли с VaR на него, потому что он видит толстые хвосты."""
    r = np.asarray(r)
    cut = np.quantile(r, 1 - level)
    return -r[r <= cut].mean()


def var_parametric(r, level=0.99):
    """VaR «по формуле», если считать доходности нормальными: среднее - z × std (z = 2.33 для 99%).
    Сравни с var_historical: если исторический больше — у рынка толстые хвосты (крупные падения чаще, чем по Гауссу)."""
    z = {0.95: 1.645, 0.99: 2.326}[level]
    r = np.asarray(r)
    return -(np.mean(r) - z * np.std(r, ddof=1))


# ------------------------------------------------------------------ Монте-Карло

def bootstrap_drawdowns(r, runs=2000, block=20, seed=1):
    """Монте-Карло «блочным бутстрепом»: перемешиваем историю кусками по `block` дней и смотрим,
    какие просадки могли бы случиться при другом порядке тех же дней. Блоки (а не отдельные дни) сохраняют
    то, что плохие дни идут сериями. Возвращает массив максимальных просадок по прогонам."""
    r = np.asarray(r)
    rng = np.random.default_rng(seed)
    n, out = len(r), []
    for _ in range(runs):
        starts = rng.integers(0, n - block, size=n // block + 1)
        path = np.concatenate([r[s:s + block] for s in starts])[:n]
        out.append(max_drawdown(path))
    return np.array(out)


# ------------------------------------------------------------------ сводка

def summary(r):
    """Все основные цифры одной таблицей (словарь)."""
    return {
        "cagr": cagr(r), "vol": volatility(r), "sharpe": sharpe(r), "sortino": sortino(r),
        "max_dd": max_drawdown(r), "calmar": calmar(r), "t": t_stat(r),
        "var99": var_historical(r), "cvar99": cvar_historical(r),
    }


def fmt(s):
    """Сводка одной строкой для печати."""
    return (f"Sharpe {s['sharpe']:.2f}  {s['cagr']:+.1%} в год  вол {s['vol']:.1%}  просадка {s['max_dd']:.1%}  "
            f"VaR99 {s['var99']:.2%}/день  CVaR99 {s['cvar99']:.2%}/день")
